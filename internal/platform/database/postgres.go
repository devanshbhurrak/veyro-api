package database

import (
	"context"
	"fmt"
	"net"
	"net/url"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"
)

// Database represents a PostgreSQL database connection pool
type Database struct {
	Pool   *pgxpool.Pool
	Config DatabaseConfig
}

// DatabaseConfig contains database connection settings
type DatabaseConfig struct {
	Host            string
	Port            int
	Database        string
	Username        string
	Password        string
	SSLMode         string
	PoolSize        int
	MinConns        int
	MaxConnLifetime time.Duration
	ConnectTimeout  time.Duration
}

// NewDatabase creates a new database connection
func NewDatabase(cfg DatabaseConfig) (*Database, error) {
	// Build the connection URL safely so credentials containing reserved
	// characters (for example @, / or :) are escaped correctly.
	dsn := url.URL{
		Scheme:   "postgresql",
		User:     url.UserPassword(cfg.Username, cfg.Password),
		Host:     net.JoinHostPort(cfg.Host, fmt.Sprintf("%d", cfg.Port)),
		Path:     "/" + cfg.Database,
		RawQuery: url.Values{"sslmode": []string{cfg.SSLMode}}.Encode(),
	}

	poolConfig, err := pgxpool.ParseConfig(dsn.String())
	if err != nil {
		return nil, fmt.Errorf("failed to parse database config: %w", err)
	}

	if cfg.PoolSize > 0 {
		poolConfig.MaxConns = int32(cfg.PoolSize)
	}
	if cfg.MinConns > 0 {
		poolConfig.MinConns = int32(cfg.MinConns)
	}
	if cfg.MaxConnLifetime > 0 {
		poolConfig.MaxConnLifetime = cfg.MaxConnLifetime
	}
	if cfg.ConnectTimeout > 0 {
		poolConfig.ConnConfig.ConnectTimeout = cfg.ConnectTimeout
	}

	pool, err := pgxpool.NewWithConfig(context.Background(), poolConfig)
	if err != nil {
		return nil, fmt.Errorf("failed to create connection pool: %w", err)
	}

	pingCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err := pool.Ping(pingCtx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("failed to ping database: %w", err)
	}

	return &Database{
		Pool:   pool,
		Config: cfg,
	}, nil
}

// Close closes the database connection pool
func (db *Database) Close() {
	if db.Pool != nil {
		db.Pool.Close()
	}
}

// GetStats returns database connection pool statistics
func (db *Database) GetStats() map[string]interface{} {
	if db.Pool == nil {
		return nil
	}

	stats := db.Pool.Stat()
	return map[string]interface{}{
		"total_conns":    stats.TotalConns(),
		"acquired_conns": stats.AcquiredConns(),
		"idle_conns":     stats.IdleConns(),
		"max_conns":      stats.MaxConns(),
	}
}

// Querier is the interface for executing database queries
// This is a minimal interface for compilation - full implementation generated by sqlc
type Querier interface {
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}

// DatabaseError represents a database error with classification
type DatabaseError struct {
	Code    string
	Message string
	Cause   error
}

// DatabaseErrorCode constants for error classification
const (
	ErrorCodeConnectionFailure    = "connection_failure"
	ErrorCodeTimeout              = "timeout"
	ErrorCodeConstraintViolation  = "constraint_violation"
	ErrorCodeForeignKeyViolation  = "foreign_key_violation"
	ErrorCodeUniqueViolation      = "unique_violation"
	ErrorCodeNotNullViolation     = "not_null_violation"
	ErrorCodeCheckViolation       = "check_violation"
	ErrorCodeSerializationFailure = "serialization_failure"
	ErrorCodeDeadlockDetected     = "deadlock_detected"
	ErrorCodeUndefinedTable       = "undefined_table"
	ErrorCodeUndefinedColumn      = "undefined_column"
	ErrorCodeSyntaxError          = "syntax_error"
	ErrorCodeGeneral              = "general"
)

// ClassifyDatabaseError classifies a database error into a standard error code
func ClassifyDatabaseError(err error) *DatabaseError {
	if err == nil {
		return nil
	}

	// Use pgx SQLSTATE codes for precise classification (preferred over string matching).
	if pgErr := PgError(err); pgErr != nil {
		switch pgErr.Code {
		case codeForeignKeyViolation:
			return &DatabaseError{Code: ErrorCodeForeignKeyViolation, Message: SafeMessage(err), Cause: err}
		case codeUniqueViolation:
			return &DatabaseError{Code: ErrorCodeUniqueViolation, Message: SafeMessage(err), Cause: err}
		case codeNotNullViolation:
			return &DatabaseError{Code: ErrorCodeNotNullViolation, Message: SafeMessage(err), Cause: err}
		case codeCheckViolation:
			return &DatabaseError{Code: ErrorCodeCheckViolation, Message: SafeMessage(err), Cause: err}
		case codeSerialization:
			return &DatabaseError{Code: ErrorCodeSerializationFailure, Message: SafeMessage(err), Cause: err}
		case codeDeadlock:
			return &DatabaseError{Code: ErrorCodeDeadlockDetected, Message: SafeMessage(err), Cause: err}
		}
	}

	// Fallback to string-based classification for connection-level errors.
	errMsg := err.Error()
	switch {
	case strings.Contains(errMsg, "connection") || strings.Contains(errMsg, "timeout") || strings.Contains(errMsg, "network"):
		return &DatabaseError{Code: ErrorCodeConnectionFailure, Message: errMsg, Cause: err}
	case strings.Contains(errMsg, "undefined table") || strings.Contains(errMsg, "does not exist"):
		return &DatabaseError{Code: ErrorCodeUndefinedTable, Message: errMsg, Cause: err}
	case strings.Contains(errMsg, "undefined column"):
		return &DatabaseError{Code: ErrorCodeUndefinedColumn, Message: errMsg, Cause: err}
	case strings.Contains(errMsg, "syntax error") || strings.Contains(errMsg, "syntax"):
		return &DatabaseError{Code: ErrorCodeSyntaxError, Message: errMsg, Cause: err}
	default:
		return &DatabaseError{Code: ErrorCodeGeneral, Message: errMsg, Cause: err}
	}
}

// IsConstraintError checks if an error is a constraint violation
func IsConstraintError(err error) bool {
	dbErr := ClassifyDatabaseError(err)
	return dbErr != nil && (dbErr.Code == ErrorCodeForeignKeyViolation ||
		dbErr.Code == ErrorCodeUniqueViolation ||
		dbErr.Code == ErrorCodeNotNullViolation ||
		dbErr.Code == ErrorCodeCheckViolation)
}

// IsRetryableError checks if an error is retryable
func IsRetryableError(err error) bool {
	dbErr := ClassifyDatabaseError(err)
	return dbErr != nil && (dbErr.Code == ErrorCodeTimeout ||
		dbErr.Code == ErrorCodeSerializationFailure ||
		dbErr.Code == ErrorCodeDeadlockDetected)
}
